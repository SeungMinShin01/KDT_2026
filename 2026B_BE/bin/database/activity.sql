DROP DATABASE IF EXISTS ACTIVITY;
create DATABASE activity;
USE ACTIVITY

CREATE TABLE CATEGORY (
    CATEGORYID INT PRIMARY KEY AUTO_INCREMENT,
    CATEGORYNAME VARCHAR(20) NOT NULL
);

CREATE TABLE MATERIAL (
    MATERIALID INT PRIMARY KEY AUTO_INCREMENT,
    MATERIALNAME VARCHAR(20) NOT NULL
);

CREATE TABLE CLOTHES(
    COLTHESID INT PRIMARY KEY AUTO_INCREMENT,
    CLOTHESNAME VARCHAR(100) NOT NULL,
    CATEGORYID INT, CONSTRAINT FOREIGN KEY (CATEGORYID) REFERENCES CATEGORY(CATEGORYID),
    MATERIALID INT, CONSTRAINT FOREIGN KEY (MATERIALID)REFERENCES MATERIAL(MATERIALID),
    IMAGEPATH VARCHAR(255) 
);

CREATE TABLE WASHINGGUIDE (
    CLOTHESID INT PRIMARY KEY AUTO_INCREMENT,
    WARTERTEMPERATURE VARCHAR(50) NOT NULL,
    WASHINGMETHOD VARCHAR(50) NOT NULL,
    RECOMMENDEDDETERGENT VARCHAR(50) NOT NULL,
    CAUTION VARCHAR(255) NOT NULL
);

CREATE TABLE WASHINGSYMBOL(
    SYMBOLID INT PRIMARY KEY AUTO_INCREMENT,
    SYMBOLNAME VARCHAR(50) NOT NULL,
    DESCRIPTION VARCHAR(255) NOT NULL,
    USAGETIP VARCHAR(255) NOT NULL,
    IMAGEPATH VARCHAR(255) NOT NULL,
    TAG VARCHAR(30) NOT NULL

);

CREATE TABLE DRYINGGUIDE (
    DRYINGID INT PRIMARY KEY AUTO_INCREMENT,
    DRYINGNAME VARCHAR(100) NOT NULL,
    METHOD VARCHAR(255) NOT NULL,
    ADVANTAGE VARCHAR(255) NOT NULL,
    CAUTION VARCHAR(255) NOT NULL,
    IMAGEPATH VARCHAR(255) NOT NULL
);

CREATE TABLE CLOTHESSYMBOLLIST (
    CLOTHESID INT,
    SYMBOLID INT,

    CONSTRAINT FOREIGN KEY (CLOTHESID) REFERENCES CLOTHES(COLTHESID),
     CONSTRAINT FOREIGN KEY (SYMBOLID) REFERENCES WASHINGSYMBOL(SYMBOLID)
);

CREATE TABLE CLOTHESDRYINGLIST(
    COLTHESID INT,
    DRYINGID INT,

    CONSTRAINT FOREIGN KEY (COLTHESID) REFERENCES CLOTHES(COLTHESID),
    CONSTRAINT FOREIGN KEY (DRYINGID) REFERENCES DRYINGGUIDE(DRYINGID)
);

